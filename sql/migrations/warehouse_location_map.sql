-- 库位图：库区 / 库位 / 储位
USE display_manufacturing;
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `warehouse_zone` (
  `zone_id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '库区ID',
  `zone_code` varchar(50) NOT NULL COMMENT '库区编码',
  `zone_name` varchar(100) NOT NULL COMMENT '库区名称',
  `warehouse_code` varchar(50) DEFAULT NULL COMMENT '关联仓库编码',
  `description` varchar(255) DEFAULT NULL COMMENT '说明',
  `sort_no` int NOT NULL DEFAULT 0 COMMENT '排序',
  `status` tinyint NOT NULL DEFAULT 1 COMMENT '状态：1启用',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`zone_id`),
  UNIQUE KEY `uk_warehouse_zone_code` (`zone_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='仓库库区';

CREATE TABLE IF NOT EXISTS `warehouse_location` (
  `location_id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '库位ID',
  `zone_id` bigint unsigned NOT NULL COMMENT '库区ID',
  `location_code` varchar(50) NOT NULL COMMENT '库位编码',
  `location_name` varchar(150) NOT NULL COMMENT '库位名称',
  `grid_rows` int NOT NULL DEFAULT 3 COMMENT '储位行数',
  `grid_cols` int NOT NULL DEFAULT 3 COMMENT '储位列数',
  `sort_no` int NOT NULL DEFAULT 0 COMMENT '排序',
  `status` tinyint NOT NULL DEFAULT 1 COMMENT '状态：1启用',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`location_id`),
  UNIQUE KEY `uk_warehouse_location_code` (`location_code`),
  KEY `idx_warehouse_location_zone` (`zone_id`),
  CONSTRAINT `fk_warehouse_location_zone` FOREIGN KEY (`zone_id`) REFERENCES `warehouse_zone` (`zone_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='仓库库位';

CREATE TABLE IF NOT EXISTS `warehouse_location_slot` (
  `slot_id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '储位ID',
  `location_id` bigint unsigned NOT NULL COMMENT '库位ID',
  `slot_code` varchar(50) NOT NULL COMMENT '储位编码',
  `row_no` int NOT NULL COMMENT '行号(从1)',
  `col_no` int NOT NULL COMMENT '列号(从1)',
  `capacity` int NOT NULL DEFAULT 1 COMMENT '容量',
  `occupied` tinyint NOT NULL DEFAULT 0 COMMENT '是否占用：0空闲 1占用',
  `material_id` bigint unsigned DEFAULT NULL COMMENT '物料ID',
  `material_name` varchar(150) DEFAULT NULL COMMENT '物料名称',
  `inventory_id` bigint unsigned DEFAULT NULL COMMENT '关联库存ID',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`slot_id`),
  UNIQUE KEY `uk_warehouse_location_slot_code` (`slot_code`),
  KEY `idx_warehouse_slot_location` (`location_id`),
  KEY `idx_warehouse_slot_material` (`material_id`),
  CONSTRAINT `fk_warehouse_slot_location` FOREIGN KEY (`location_id`) REFERENCES `warehouse_location` (`location_id`),
  CONSTRAINT `fk_warehouse_slot_material` FOREIGN KEY (`material_id`) REFERENCES `material` (`material_id`),
  CONSTRAINT `fk_warehouse_slot_inventory` FOREIGN KEY (`inventory_id`) REFERENCES `inventory` (`inventory_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='仓库储位';

